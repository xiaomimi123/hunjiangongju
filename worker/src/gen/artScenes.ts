import { pickSubset } from '@mixcut/db'

// 配图不再跟着文案走。
//
// 旧做法是让 LLM 把每段口播提炼成一句画面描述再去生图，结果必然是逐句配插画——
// 「手还能端起自己的碗」画一只碗、「台阶看不见」画石阶、「文字长出翅膀」画羽毛。
// 换画风只会得到「梵高风格的碗」，主体依旧被文案锁死。
//
// 现在改成自由创作：主体不来自文案，只给一个场景方向 + 框架的画风提示词。
// 之所以还要「场景方向」而不是六段发同一句提示词——同提示词会让生图模型产出六张
// 近乎雷同的画。方向由 genTaskId 派生的确定性随机源分配：同任务重跑结果一致，
// 不同任务必然不同（本仓禁用 Math.random）。
// 场景池只负责一件事：让同一条片子的 N 张图彼此不同。同一句提示词发 N 次，生图模型会给出
// N 张近乎雷同的画。
//
// 池子里的方向必须**与流派无关**。原先这一池全是梵高的母题（向日葵田 / 鸢尾花丛 /
// 柏树与旋转的云 / 星空下的夜色），画风换成达芬奇时题材还是梵高的——「同一模板、不同配图
// 风格」这个产品目标直接卡死在这里。现在只留通用的时间、天气、地貌与光线方向，
// 具体画成什么样完全由画风提示词决定。
export const ART_SCENES = [
  '静谧的窗边',
  '雨后的街道',
  '远山与云海',
  '海边的黄昏',
  '林间的小径',
  '旧书房的一角',
  '夜色中的城市',
  '开阔的田野与远树',
  '溪流与石桥',
  '晨光中的庭院',
  '雪后的原野',
  '荒原与孤树',
  '湖面与倒影',
  '楼梯间的光影',
  '花园的一隅',
  '暮色中的长桥',
]

// 负向提示词。原实现在这里硬禁人物（人/人脸/portrait/face/hands…），开场要的卡通人物
// 头像根本出不来。人物与否改由画风提示词决定——**只保留禁文字**：文案被画进图里会与
// 字幕层叠字、糊成乱码，这是渲染层的硬需求，不能交给提示词碰运气。
export const IMAGE_NEGATIVE_PROMPT =
  '文字, 字, 汉字, 字母, 单词, 书法, 标题, 字幕, 水印, text, letters, words, caption, watermark, signature'

/**
 * 纯函数：按 seed 给 n 个分镜各派一个场景方向。
 * 先整池洗牌再按下标取，因此分镜数不超过池子大小时互不重复；超出则循环复用
 * （仍是洗牌后的顺序，不会紧挨着重复同一个）。
 */
export function pickArtScenes(seed: string, n: number): string[] {
  if (n <= 0) return []
  const shuffled = pickSubset(ART_SCENES, ART_SCENES.length, seed)
  return Array.from({ length: n }, (_, i) => shuffled[i % shuffled.length])
}

/**
 * 纯函数：拼单张配图的提示词。
 * 禁文字约束在此保底——文案绝不能被画进图里，否则会和字幕层叠字、糊成乱码。
 */
export function buildFreeArtPrompt(stylePrompt: string, scene: string): string {
  // 尾巴从「竖屏背景，纯画面，…」改成「竖屏构图，…」：
  // 「背景」把每张图都框死成背景板，人物特写这类槽位说不通；
  // 「纯画面」语义含糊，会被模型读成「不要主体」，与卡通头像直接打架。
  return [stylePrompt, scene, '竖屏构图，不出现任何文字、字幕或水印']
    .map((s) => (s ?? '').trim())
    .filter(Boolean)
    .join('，')
}
